/* ---- function values ---- */
static inline void jig_fn_retain(jig_fn *f) {
    if (f->env) jig_rc_inc(&f->env->rc);
}
static inline void jig_fn_release(jig_fn *f) {
    if (f->env && jig_rc_dec(&f->env->rc)) f->env->drop(f->env);
}

