/* The Jig runtime: reference-counted copy-on-write strings, lists and maps, checked
 * arithmetic, formatting and effects. Generated code includes this header.
 *
 * Conventions: a NULL string, list or map is empty, so zero-initialized values are valid.
 * Arguments are borrowed; results are owned. Objects with a negative reference count are
 * static and never freed. */
