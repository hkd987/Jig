#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct Intrinsic {
    pub op: Op,
    /// Type arguments of the instance (element types, the shown type, ...).
    pub tys: Box<[Ty]>,
    /// For integer methods: the integer type.
    pub int: Option<IntTy>,
}

impl Intrinsic {
    pub fn new(op: Op, tys: Vec<Ty>) -> Intrinsic {
        Intrinsic { op, tys: tys.into_boxed_slice(), int: None }
    }
}

/// Map a bodiless std function to its intrinsic.
pub fn lookup(pkg_path: &str, recv: Option<TyKey>, name: &str) -> Option<(Op, Option<IntTy>)> {
    use Op::*;
    let int = match recv {
        Some(TyKey::Int(k)) => Some(k),
        _ => None,
    };
    let op = match (pkg_path, recv, name) {
        ("<prelude>", None, "panic") => Panic,
        ("<prelude>", None, "assert") => Assert,
        ("<prelude>", Some(TyKey::Int(_)), n) => match n {
            "abs" => IntAbs,
            "min" => IntMin,
            "max" => IntMax,
            "pow" => IntPow,
            "wrapping_add" => WrappingAdd,
            "wrapping_sub" => WrappingSub,
            "wrapping_mul" => WrappingMul,
            _ => return None,
        },
        ("<prelude>", Some(TyKey::Float), n) => match n {
            "abs" => FloatAbs,
            "sqrt" => Sqrt,
            "floor" => Floor,
            "ceil" => Ceil,
            "round" => Round,
            "min" => FloatMin,
            "max" => FloatMax,
            "is_nan" => IsNan,
            _ => return None,
        },
        ("<prelude>", Some(TyKey::Char), n) => match n {
            "is_digit" => IsDigit,
            "is_alpha" => IsAlpha,
            "is_alnum" => IsAlnum,
            "is_space" => IsSpace,
            "is_upper" => IsUpper,
            "is_lower" => IsLower,
            "to_upper" => CharToUpper,
            "to_lower" => CharToLower,
            _ => return None,
        },
        ("<prelude>", Some(TyKey::Str), n) => match n {
            "len" => StrLen,
            "is_empty" => StrIsEmpty,
            "contains" => StrContains,
            "starts_with" => StartsWith,
            "ends_with" => EndsWith,
            "find" => StrFind,
            "split" => Split,
            "lines" => Lines,
            "trim" => Trim,
            "replace" => Replace,
            "repeat" => Repeat,
            "to_upper" => StrToUpper,
            "to_lower" => StrToLower,
            "to_int" => ToInt,
            "to_float" => ToFloat,
            "bytes" => Bytes,
            "chars" => Chars,
            "from_chars" => FromChars,
            "from_bytes" => FromBytes,
            _ => return None,
        },
        ("<prelude>", Some(TyKey::List), n) => match n {
            "new" => ListNew,
            "len" => ListLen,
            "is_empty" => ListIsEmpty,
            "push" => Push,
            "pop" => Pop,
            "get" => Get,
            "insert" => Insert,
            "remove" => Remove,
            "clear" => Clear,
            "extend" => Extend,
            "reverse" => Reverse,
            "swap" => Swap,
            "truncate" => Truncate,
            "repeat" => ListRepeat,
            "sort" => Sort,
            "sort_by" => SortBy,
            _ => return None,
        },
        ("<prelude>", Some(TyKey::Map), n) => match n {
            "new" => MapNew,
            "len" => MapLen,
            "is_empty" => MapIsEmpty,
            "get" => MapGet,
            "insert" => MapInsert,
            "remove" => MapRemove,
            "contains" => MapContains,
            "keys" => Keys,
            "values" => Values,
            "entries" => Entries,
            _ => return None,
        },
        ("<prelude>", Some(TyKey::Set), n) => match n {
            "new" => SetNew,
            "len" => SetLen,
            "is_empty" => SetIsEmpty,
            "insert" => SetInsert,
            "remove" => SetRemove,
            "contains" => SetContains,
            "items" => Items,
            _ => return None,
        },
        ("std/io", None, n) => match n {
            "print" => Print,
            "println" => Println,
            "eprintln" => Eprintln,
            "read_line" => ReadLine,
            "read_all" => ReadAll,
            _ => return None,
        },
        ("std/fs", None, n) => match n {
            "read" => FsRead,
            "write" => FsWrite,
            "exists" => FsExists,
            "list" => FsList,
            _ => return None,
        },
        ("std/os", None, n) => match n {
            "args" => Args,
            "env" => EnvVar,
            "exit" => Exit,
            _ => return None,
        },
        ("std/time", None, "now_ms") => NowMs,
        ("std/time", None, "now_ns") => NowNs,
        ("std/time", None, "sleep") => Sleep,
        ("std/sim", None, n) => match n {
            "stdout" => SimStdout,
            "stderr" => SimStderr,
            "set_stdin" => SimSetStdin,
            "set_args" => SimSetArgs,
            "set_env" => SimSetEnv,
            "set_file" => SimSetFile,
            "file" => SimFile,
            "remove_file" => SimRemoveFile,
            "set_time" => SimSetTime,
            "advance" => SimAdvance,
            "seed" => SimSeed,
            "reply" => SimReply,
            "requests" => SimRequests,
            "connect" => SimConnect,
            "answers" => SimAnswers,
            _ => return None,
        },
        ("std/net", None, "request") => NetRequest,
        ("std/net", None, "serve") => NetServe,
        ("std/rand", None, "int") => RandInt,
        ("std/rand", None, "float") => RandFloat,
        ("std/task", None, n) => match n {
            "all" => TaskAll,
            "map" => TaskMap,
            "both" => TaskBoth,
            _ => return None,
        },
        ("std/math", None, n) => match n {
            "sin" => Sin,
            "cos" => Cos,
            "tan" => Tan,
            "atan2" => Atan2,
            "exp" => Exp,
            "ln" => Ln,
            "log10" => Log10,
            "pow" => Pow,
            _ => return None,
        },
        _ => return None,
    };
    Some((op, int))
}
