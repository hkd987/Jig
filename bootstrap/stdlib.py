#!/usr/bin/env python3
"""Writes selfhost/sema/stdlib.jig: the standard library (compiler/std/*.jig), the C runtime
(compiler/runtime), the diagnostic code registry (compiler/src/diag/codes.rs) and the
language reference (docs/reference.md) as string constants, so jigc carries them as the
bootstrap compiler does (`include_str!`).

usage: stdlib.py [--check]   (--check fails instead if the file is stale)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "selfhost", "sema", "stdlib.jig")


def literal(text):
    out = ['"']
    for c in text:
        if c == '"':
            out.append('\\"')
        elif c == "\\":
            out.append("\\\\")
        elif c == "\n":
            out.append("\\n")
        elif c == "\t":
            out.append("\\t")
        elif c == "\r":
            out.append("\\r")
        elif ord(c) < 32:
            out.append("\\u{%x}" % ord(c))
        else:
            out.append(c)
    out.append('"')
    return "".join(out)


def rust_str(src, i):
    """The Rust string literal starting at src[i] (a quote): its value and the index after it."""
    i += 1
    out = []
    escapes = {"n": "\n", "t": "\t", "r": "\r", "0": "\0", "\\": "\\", '"': '"', "'": "'"}
    while True:
        c = src[i]
        if c == '"':
            return "".join(out), i + 1
        if c == "\\":
            n = src[i + 1]
            if n == "\n":
                # A line continuation: the line break and the next line's leading blanks go.
                i += 2
                while src[i] in " \t\r\n":
                    i += 1
                continue
            if n == "u":
                j = src.index("}", i)
                out.append(chr(int(src[i + 3 : j], 16)))
                i = j + 1
                continue
            out.append(escapes[n])
            i += 2
            continue
        out.append(c)
        i += 1


def codes():
    """The diagnostic code registry (compiler/src/diag/codes.rs): (number, slug, summary,
    explanation) in order."""
    src = open(os.path.join(ROOT, "compiler", "src", "diag", "codes.rs"), encoding="utf-8").read()
    body = src[src.index("codes! {") :]
    out = []
    pos = 0
    pat = re.compile(r"\bE\d{4} = (\d+),\s*")
    while True:
        m = pat.search(body, pos)
        if not m:
            return out
        i = m.end()
        fields = []
        for _ in range(3):
            while body[i] != '"':
                i += 1
            v, i = rust_str(body, i)
            fields.append(v)
        out.append((int(m.group(1)), *fields))
        pos = i


def render():
    std = os.path.join(ROOT, "compiler", "std")
    rt = os.path.join(ROOT, "compiler", "runtime")
    names = sorted(n for n in os.listdir(std) if n.endswith(".jig"))
    rt_names = sorted(n for n in os.listdir(rt) if n.endswith((".c", ".h")))
    lines = [
        "// Generated by bootstrap/stdlib.py; do not edit. The standard library, C runtime, diagnostic",
        "// codes and language reference jigc carries, as the bootstrap compiler carries them",
        "// (`include_str!`).",
        "",
        "/// The text of standard library file `name` (`io.jig`, `prelude.jig`, ...).",
        "fn std_source(name: Str) -> Option<Str> {",
        "  return match name {",
    ]
    for n in names:
        lines.append('    "%s" => Some(%s)' % (n, const_name("STD_", n)))
    lines += ["    _ => None", "  }", "}", ""]
    lines += [
        "/// The text of C runtime file `name` (`jig_rt.c`, `jig_rt.h`).",
        "fn runtime_source(name: Str) -> Option<Str> {",
        "  return match name {",
    ]
    for n in rt_names:
        lines.append('    "%s" => Some(%s)' % (n, const_name("RT_", n)))
    lines += ["    _ => None", "  }", "}", ""]
    lines += [
        "/// A diagnostic code's slug, summary and explanation (`jig explain`).",
        "fn code_info(code: Int) -> Option<(Str, Str, Str)> {",
        "  return match code {",
    ]
    table = codes()
    for n, _, _, _ in table:
        lines.append("    %d => Some((E%04d_SLUG, E%04d_SUMMARY, E%04d_EXPLAIN))" % (n, n, n, n))
    lines += ["    _ => None", "  }", "}", ""]
    for n, slug, summary, explain in table:
        lines.append("const E%04d_SLUG: Str = %s" % (n, literal(slug)))
        lines.append("const E%04d_SUMMARY: Str = %s" % (n, literal(summary)))
        lines.append("const E%04d_EXPLAIN: Str = %s" % (n, literal(explain)))
    lines.append("")
    with open(os.path.join(ROOT, "docs", "reference.md"), encoding="utf-8") as f:
        lines.append("/// The language reference (`jig reference`).")
        lines.append("const REFERENCE: Str = %s" % literal(f.read()))
        lines.append("")
    for d, prefix, ns in [(std, "STD_", names), (rt, "RT_", rt_names)]:
        for n in ns:
            with open(os.path.join(d, n), encoding="utf-8") as f:
                lines.append("const %s: Str = %s" % (const_name(prefix, n), literal(f.read())))
            lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def const_name(prefix, name):
    return prefix + name.replace(".", "_").upper()


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("selfhost/sema/stdlib.jig is stale: run bootstrap/update.sh")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    main()
